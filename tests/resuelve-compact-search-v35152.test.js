'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'public/resuelve.html'),'utf8');
const js=fs.readFileSync(path.join(root,'public/resuelve-v350.js'),'utf8');
const css=fs.readFileSync(path.join(root,'public/resuelve-v350.css'),'utf8');
test('V3.5.15.2: búsqueda visible, filtros inicialmente plegados y controles accesibles',()=>{
 const form=html.slice(html.indexOf('<form id="questionSearchForm"'),html.indexOf('</form>',html.indexOf('<form id="questionSearchForm"')));
 assert.ok(form.length>0);
 assert.match(form,/id="questionSearch" type="search"/);
 assert.match(form,/placeholder="Ej.: ayuda para hacer un trámite"/);
 assert.match(form,/class="secondary resuelve-search-submit">Buscar<\/button>/);
 assert.match(form,/id="questionMoreFiltersToggle"[\s\S]*?aria-expanded="false" aria-controls="questionAdvancedFilters">Más filtros/);
 assert.match(form,/id="questionAdvancedFilters" class="resuelve-search-advanced" hidden/);
 assert.ok(form.indexOf('questionSearch"')<form.indexOf('questionAdvancedFilters"'));
 const advanced=form.slice(form.indexOf('id="questionAdvancedFilters"'));
 assert.match(advanced,/id="questionCategoryFilter"/);
 assert.match(advanced,/id="questionProfessionalFilter"/);
 assert.match(advanced,/id="questionSearchClear"/);
 assert.doesNotMatch(form.slice(0,form.indexOf('id="questionAdvancedFilters"')),/id="questionCategoryFilter"|id="questionProfessionalFilter"/);
 assert.match(css,/\.resuelve-search \.resuelve-search-advanced\[hidden\]\{display:none!important\}/);
 assert.match(css,/\.resuelve-search \.resuelve-search-submit\{[^}]*min-height:44px/s);
 assert.match(css,/@media\(max-width:650px\)/);
});
