test('V3.2.63.2 strictly validates contact return path, seller and listing; rejects foreign and mismatched destinations',()=>{
 const js=read('public/app.js');
 const start=js.indexOf('function validPublicEntry(value){'),end=js.indexOf('function loadPublicEntry(){',start);
 assert.ok(start>=0&&end>start);
 const sandbox={Date};
 vm.createContext(sandbox);vm.runInContext(js.slice(start,end),sandbox);
 const valid=(key,path)=>vm.runInContext('validPublicEntry('+JSON.stringify({type:'marketplace_contact',key,path,ts:Date.now()})+')',sandbox);
 assert.equal(valid('5','/marketplace?contact=mundotaza&listing=5').path,'/marketplace?contact=mundotaza&listing=5');
 assert.equal(valid('5','/marketplace?contact=mundotaza&listing=6'),null);
 assert.equal(valid('5','https://evil.test/marketplace?contact=mundotaza&listing=5'),null);
 assert.equal(valid('5','//evil.test/marketplace?contact=mundotaza&listing=5'),null);
 assert.equal(valid('5','/marketplace?contact=%2F%2Fevil.test&listing=5'),null);
 assert.equal(valid('5','/marketplace?contact=mundotaza&listing=5&other=1'),null);
 assert.equal(valid('0','/marketplace?contact=mundotaza&listing=0'),null);
});
