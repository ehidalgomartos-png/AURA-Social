'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const file=name=>fs.readFileSync(path.join(root,name),'utf8');

test('V3.5.15.1: cabecera mobile-first da prioridad a pedir ayuda y a las peticiones',()=>{
 const html=file('public/resuelve.html');
 const css=file('public/resuelve-v350.css');
 const js=file('public/resuelve-v350.js');
 const hero=html.slice(html.indexOf('<section class="hero"'),html.indexOf('</section>',html.indexOf('<section class="hero"')));
 assert.match(hero,/<h1 id="hero-title">Pide ayuda\. Comparte lo que sabes\.<\/h1>/);
 assert.match(hero,/id="heroActions" class="hero-actions"/);
 assert.match(hero,/id="askButton" class="primary hero-main-action"[^>]*hidden>Pedir ayuda<\/button>/);
 assert.match(hero,/id="joinResuelveButton" class="primary hero-main-action"[^>]*hidden>Pedir ayuda<\/button>/);
 assert.match(hero,/id="loginResuelveButton" class="secondary hero-login"[^>]*hidden>Ya tengo cuenta<\/button>/);
 assert.match(hero,/id="viewQuestionsLink" href="#questions" class="secondary hero-explore">Ver peticiones<\/a>/);
 assert.match(hero,/href="#solutions" class="hero-tertiary">Ver soluciones útiles<\/a>/);
 assert.ok(hero.indexOf('hero-main-action')<hero.indexOf('hero-login'));
 assert.ok(hero.indexOf('hero-login')<hero.indexOf('hero-explore'));
 assert.ok(hero.indexOf('hero-explore')<hero.indexOf('hero-tertiary'));
 assert.match(hero,/Nadie tiene que comprar ni contratar nada/);
 assert.doesNotMatch(hero,/Crear cuenta y pedir ayuda/);
 assert.match(css,/\.hero-actions\.is-authenticated \.hero-explore\{grid-column:1\/-1\}/);
 assert.match(css,/\.hero-actions \.hero-main-action\{[^}]*grid-column:1\/-1/s);
 assert.match(css,/@media\(max-width:650px\)\{[\s\S]*?\.hero\{[\s\S]*?padding:17px 17px 16px/s);
 assert.match(css,/@media\(max-width:355px\)/);
 assert.match(js,/el\('heroActions'\)\.classList\.toggle\('is-authenticated',!guest\)/);
 assert.match(js,/el\('joinResuelveButton'\)\.addEventListener\('click',\(\)=>openAuth\('register'\)\)/);
 assert.match(js,/el\('askButton'\)\.addEventListener\('click'/);
 assert.match(js,/el\('askPanel'\)\.scrollIntoView/);
 assert.doesNotMatch(js,/if\(!state\.user\)message\('Puedes leer las peticiones sin registrarte/);
 assert.match(html,/id="resuelveRegisterForm"/);
 assert.match(html,/id="resuelveLoginForm"/);
 assert.match(html,/id="questions"/);
 assert.match(html,/id="solutions"/);
});
